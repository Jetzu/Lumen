#!/usr/bin/env python3
"""Regenerate the README screenshots in docs/images (rendered by Lumen itself).

    .venv/bin/python docs/make_gallery.py            # needs Playwright (pip install playwright) and Google Chrome
    .venv/bin/python docs/make_gallery.py --agent    # also the Agent Chat shot: a real prompt through your Claude Code

Starts a throwaway Lumen server (its own LUMEN_HOME), drives it with Playwright on the installed Google Chrome (no
browser download) and writes one PNG per README gallery entry.  Every image is a bundled sample (Blobs, the synthetic
nuclei / cells / time-lapse samples generated by Lumen, the MRI stack), so the shots are reproducible."""
from __future__ import annotations

import json
import os
import socket
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "images"
W, H = 1600, 960


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def server_python() -> str:
    """The Python that runs Lumen: $LUMEN_PYTHON, the repository's .venv, or this interpreter."""
    for cand in (os.environ.get("LUMEN_PYTHON"), ROOT / ".venv" / "bin" / "python", ROOT / ".venv" / "Scripts" / "python.exe"):
        if cand and Path(cand).is_file():
            return str(cand)
    return sys.executable


class Lumen:
    def __init__(self) -> None:
        self.port = free_port()
        self.url = f"http://127.0.0.1:{self.port}"
        self.home = tempfile.mkdtemp(prefix="lumen-gallery-")
        self.proc = subprocess.Popen([server_python(), "-m", "lumen", "--no-browser", "--host", "127.0.0.1", "--port", str(self.port)],
                                     cwd=ROOT, env={**os.environ, "LUMEN_HOME": self.home}, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for _ in range(300):
            try:
                urllib.request.urlopen(self.url + "/api/jobs", timeout=1)
                return
            except Exception:  # noqa: BLE001
                time.sleep(0.1)
        raise SystemExit("Lumen did not start")

    def run(self, op: str, params: dict | None = None, image_id: str | None = None) -> dict:
        req = urllib.request.Request(f"{self.url}/api/ops/{op}/run", method="POST", headers={"Content-Type": "application/json"},
                                     data=json.dumps({"params": params or {}, "image_id": image_id, "scope": "stack"}).encode())
        with urllib.request.urlopen(req, timeout=600) as r:
            return json.loads(r.read())

    def reset(self) -> None:
        st = json.loads(urllib.request.urlopen(self.url + "/api/state").read())
        for im in st["images"]:
            urllib.request.urlopen(urllib.request.Request(f"{self.url}/api/images/{im['id']}", method="DELETE"))
        urllib.request.urlopen(urllib.request.Request(f"{self.url}/api/results", method="DELETE"))
        urllib.request.urlopen(urllib.request.Request(f"{self.url}/api/rois", method="DELETE"))

    def stop(self) -> None:
        self.proc.terminate()
        self.proc.wait(10)


def main(argv: list[str]) -> int:
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    lm = Lumen()
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch(channel="chrome", args=["--enable-unsafe-swiftshader", "--use-angle=swiftshader"])
            pg = browser.new_page(viewport={"width": W, "height": H}, device_scale_factor=1)
            pg.goto(lm.url)
            pg.wait_for_selector(".rail")

            def settle(t: float = 0.8) -> None:
                pg.wait_for_timeout(int(t * 1000))

            def shot(name: str) -> None:
                settle(0.5)
                pg.screenshot(path=str(OUT / f"{name}.png"))
                print("wrote", OUT / f"{name}.png")

            def panels(**open_: bool) -> None:
                for key, want in open_.items():
                    head = pg.locator(f"#section-head-{key}")
                    if head.count() and (head.get_attribute("aria-expanded") == "true") != want:
                        head.click()
                        settle(0.2)

            def theme(t: str) -> None:
                cur = pg.evaluate("document.documentElement.dataset.theme || 'dark'")
                if cur != t:
                    pg.locator('button[aria-label="Toggle theme"]').click()
                    settle(0.4)

            # 1 workspace: a three-channel composite with the inspector
            theme("dark")
            lm.run("file.sample", {"name": "Synthetic nuclei (3 channels)"})
            settle(1.5)
            panels(display=True, threshold=False, workflows=False, rois=False, results=False, tracks=False)
            shot("workspace")

            # 2 threshold + particles on Blobs
            lm.reset()
            r = lm.run("file.sample", {"name": "Blobs"})
            iid = (r.get("new_images") or [None])[0]
            lm.run("threshold.compute", {"method": "Otsu", "dark_background": True}, iid)  # Blobs: bright blobs on a dark background
            settle(1.0)
            panels(display=False, threshold=True, rois=False, results=False, workflows=False)
            shot("threshold")
            lm.run("analyze.particles", {"min_size": 20, "show": "Nothing", "display_results": True, "clear_results": True, "summarize": False, "add_to_manager": True}, iid)
            settle(1.2)
            panels(threshold=False, rois=True, results=True)
            pg.locator('button:has-text("Show all")').first.click() if pg.locator('button:has-text("Show all")').count() else None
            shot("particles")

            # 3 command palette and live preview (on a clean image)
            lm.reset()
            lm.run("file.sample", {"name": "Cell nuclei (fluorescence)"})
            settle(1.2)
            panels(rois=False, results=False, display=True)
            pg.locator('button:has-text("Auto")').first.click()
            settle(0.4)
            pg.keyboard.press("Meta+k" if sys.platform == "darwin" else "Control+k")
            settle(0.3)
            pg.keyboard.type("gauss")
            settle(0.5)
            shot("palette")
            pg.keyboard.press("Enter")
            settle(0.8)
            sig = pg.locator(".sheet input, .op-sheet input").first
            sig.fill("4")
            sig.press("Tab")
            settle(1.5)
            shot("preview")
            pg.keyboard.press("Escape")

            # 4 3-D view of the cells stack
            lm.reset()
            lm.run("file.sample", {"name": "Cells (3-D, 2 channels)"})
            settle(1.5)
            panels(volume=True, ortho=False, display=False, rois=False, results=False)
            settle(3.0)
            pg.locator("#section-head-volume").scroll_into_view_if_needed()
            pg.evaluate("document.querySelector('#section-head-volume').scrollIntoView({block: 'start'})")
            settle(1.0)
            shot("volume")
            panels(volume=False)

            # 5 tracking on the synthetic time-lapse
            lm.reset()
            r = lm.run("file.sample", {"name": "Nuclei timelapse (synthetic)"})
            lm.run("tracking.track", {}, (r.get("new_images") or [None])[0])
            settle(1.5)
            panels(tracks=True, display=False, rois=False, results=False)
            shot("tracking")
            panels(tracks=False)

            # 6 scripting: an ImageJ macro in the script editor, the recorder beside it
            lm.reset()
            lm.run("file.sample", {"name": "Blobs"})
            settle(1.0)
            panels(script=True, display=False, rois=False, results=False)
            pg.locator("select.script-lang").select_option("ijm")
            settle(0.3)
            pg.locator(".script-editor textarea").first.fill('run("Gaussian Blur...", "sigma=1");\nsetAutoThreshold("Otsu dark");\nrun("Analyze Particles...", "size=20-Infinity display clear add");\nprint("blobs: " + nResults);\n')
            pg.locator('button:has-text("Run")').first.click()
            settle(2.0)
            pg.evaluate("document.querySelector('#section-head-script').scrollIntoView({block: 'start'})")
            settle(0.6)
            shot("scripting")
            panels(script=False)

            # 7 light theme with ROIs
            theme("light")
            lm.reset()
            r = lm.run("file.sample", {"name": "Cell nuclei (fluorescence)"})
            settle(1.2)
            panels(display=True, rois=True)
            pg.locator('button:has-text("Auto")').first.click()
            settle(0.8)
            shot("light")
            theme("dark")

            # 8 Agent Chat: a real prompt through the user's Claude Code (only with --agent)
            if "--agent" in argv:
                lm.reset()
                lm.run("file.sample", {"name": "Blobs"})
                settle(1.0)
                pg.locator(".agent-btn").click()
                fr = pg.frame_locator(".agent-dock iframe")
                fr.locator("#prompt").wait_for()
                settle(2.0)
                fr.locator("#prompt").fill("Count the blobs in this image (Otsu threshold, particles of at least 20 px) and tell me their mean area.")
                fr.locator("#prompt").press("Enter")
                for _ in range(240):  # up to 2 minutes
                    settle(0.5)
                    if fr.locator("#status.hidden").count() and fr.locator(".e-assistant").count():
                        break
                settle(1.5)
                shot("agent")
            browser.close()
    finally:
        lm.stop()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
